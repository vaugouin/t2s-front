if (!function_exists('get_movie_string')) {
    function get_movie_string($key, $lang = null) {
        global $movie_strings, $struilang;

        // Use provided language or fallback to UI language
        $language = $lang ?? $struilang;

        // Fallback to English if string doesn't exist in selected language
        if (!isset($movie_strings[$language][$key])) {
            $language = 'en';
        }

        return $movie_strings[$language][$key] ?? $key;
    }
}

